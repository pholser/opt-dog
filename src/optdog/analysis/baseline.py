"""Compare human programs, the greedy baseline and the finish lower bound on every parsed show.

    python -m optdog.analysis.baseline        # writes docs/baseline.md

Exhibitor conflicts (S1) use the synthetic entries in data/synthetic (seed 0).
"""

from __future__ import annotations

from pathlib import Path

from optdog.domain import fmt_time
from optdog.instance import instance_from_program
from optdog.io.program_csv import read_entries, read_program
from optdog.params import ShowParameters
from optdog.solve.bounds import finish_lower_bound
from optdog.solve.greedy import greedy_program
from optdog.validate import validate

ROOT = Path(__file__).resolve().parents[3]
PARSED = ROOT / "data" / "parsed"
SYNTH = ROOT / "data" / "synthetic"
OUT = ROOT / "docs" / "baseline.md"


def _t(x: float) -> str:
    return fmt_time(int(round(x)))


def rows(params: ShowParameters):
    for d in sorted(PARSED.glob("*/*")):
        if not (d / "schedule.csv").exists():
            continue
        human = read_program(d)
        synth = SYNTH / d.parent.name / d.name / "seed-0"
        if synth.exists():
            human.show.entries = read_entries(synth, human)
        show = instance_from_program(human)
        bound = finish_lower_bound(show, params)
        greedy = greedy_program(show, params)
        rh, rg = validate(human, params), validate(greedy, params)
        yield d.name, bound, human, rh, greedy, rg


def render(params: ShowParameters | None = None) -> str:
    p = params or ShowParameters()
    lines = [
        "# Baseline: human programs vs greedy vs lower bound",
        "",
        "Generated by `python -m optdog.analysis.baseline`. Times are planned times at the judges' rates;",
        "group and BIS durations are the conservative upper bounds of SPEC §2.5, so absolute finish",
        "times run late. Compare the columns with each other, not with real show close.",
        "",
        "- **LB**: `max(judge-chain, ring-capacity)` lower bound on BIS end (`solve/bounds.py`).",
        "- **Human**: the published program, re-timed by the validator (groups start at the published time).",
        "- **Greedy**: `solve/greedy.py` on the instance derived from the same program",
        "  (special-attraction blocks pinned, all-breed events re-planned).",
        "- **Gap**: minutes of finish above the lower bound.",
        "- **S1**: exhibitor-conflict minutes, synthetic exhibitors, seed 0.",
        "",
        "| Show | LB | Human groups | Human finish | gap | Greedy groups | Greedy finish | gap | Human hard | Greedy hard | S1 human | S1 greedy | Obj human | Obj greedy |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    gaps_h, gaps_g = [], []
    for name, bound, human, rh, greedy, rg in rows(p):
        lb = bound.value
        fh, fg = rh.timeline.finish, rg.timeline.finish
        gaps_h.append(fh - lb)
        gaps_g.append(fg - lb)
        hard_h = ", ".join(sorted({v.code for v in rh.violations})) or "–"
        hard_g = ", ".join(sorted({v.code for v in rg.violations})) or "–"
        lines.append(
            f"| {name} | {_t(lb)} | {rh.metrics['groups_start']} | {_t(fh)} | {fh - lb:.0f} | "
            f"{rg.metrics['groups_start']} | {_t(fg)} | {fg - lb:.0f} | {hard_h} | {hard_g} | "
            f"{rh.soft.get('S1_conflict_min', 0):.0f} | {rg.soft.get('S1_conflict_min', 0):.0f} | "
            f"{rh.objective:.0f} | {rg.objective:.0f} |"
        )
    n = len(gaps_h)
    lines += [
        "",
        f"Mean gap to the lower bound: human {sum(gaps_h) / n:.0f} min, greedy {sum(gaps_g) / n:.0f} min "
        f"(greedy finishes earlier on {sum(1 for a, b in zip(gaps_h, gaps_g) if b < a)} of {n} days).",
        "",
        "Hard-constraint codes: V1 is a judge over 175 entries, an input problem that no schedule can fix.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUT.write_text(render())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
